create table ph.suppliers (
  id        integer generated by default as identity (start with 10000) primary key,
  code      text unique check (code ~ '^[A-Z0-9_]{2,20}$'),      -- NEWCITY, REDA, ELFATH, AMG, PHARMA, IBNSINA
  name      text not null unique check (char_length(name) between 2 and 80),
  kind      text not null check (kind in ('warehouse', 'company')),   -- مخزن / شركة توزيع
  phone     text check (phone ~ '^[0-9]{8,15}$'),
  legacy_id text unique,                                             -- رقمه في فارمافلاي (للنقل بس)
  active    boolean not null default true
);

-- المناديب: المورد له أكتر من مندوب (نهار/ليل). chat_name = اسمه في جهات اتصال الواتس: «مخزن ... (اسم)»
create table ph.supplier_reps (
  id          integer generated always as identity primary key,
  supplier_id integer not null references ph.suppliers (id),
  chat_name   text not null unique check (char_length(chat_name) between 2 and 80),
  phone       text check (phone ~ '^[0-9]{8,15}$'),
  shift       text not null default 'any' check (shift in ('day', 'night', 'any')),
  active      boolean not null default true
);

-- اسم الصنف عند المورد ← صنفنا (اللي البوت اتعلمه: أكتر من 20 ألف اسم)
create table ph.supplier_item_names (
  supplier_id   integer not null references ph.suppliers (id),
  name_norm     text not null check (char_length(name_norm) between 2 and 250),
  supplier_name text not null,
  item_id       bigint not null references ph.items (id),
  confirmed     boolean not null default false,       -- المالك قال «أيوه، ده هو»
  first_seen    date not null default current_date,
  last_seen     date not null default current_date,
  primary key (supplier_id, name_norm)
);
create index on ph.supplier_item_names (item_id);

-- الرقم بنفس قواعد أداة التواصل (normPhone): أرقام عربي أو فارسي، 01x مصري ← 201x، 00 ← دولي. غلط = null
create function ph.norm_phone(v text) returns text
language plpgsql immutable set search_path = '' as $$
declare p text := btrim(coalesce(v, ''));
begin
  p := translate(p, '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789');
  p := regexp_replace(p, '[\s()\-\u200e\u200f]', '', 'g');
  if p !~ '^\+?[0-9]+$' then return null; end if;
  p := ltrim(p, '+');
  if p like '00%' then p := substr(p, 3); end if;
  if p ~ '^0?1[0125][0-9]{8}$' then return '20' || regexp_replace(p, '^0', ''); end if;
  if p like '20%' then return case when p ~ '^201[0125][0-9]{8}$' then p end; end if;
  return case when p ~ '^[1-9][0-9]{7,14}$' then p end;
end $$;

create table ph.customers (
  id           bigint generated by default as identity (start with 100000) primary key,
  name         text not null check (char_length(name) between 1 and 80),
  phone        text unique check (phone ~ '^[0-9]{8,15}$'),   -- نفس شكل أداة التواصل: 2010xxxxxxxx
  other_phones text[] not null default '{}',
  area         text check (char_length(area) <= 80),
  address      text check (char_length(address) <= 300),
  credit_limit numeric(12, 2) not null default 0 check (credit_limit >= 0),   -- 0 = مفيش آجل
  outreach_day smallint check (outreach_day between 0 and 6),                 -- مجموعة التواصل: 0 = السبت … 6 = الجمعة
  whatsapp_ok  boolean not null default true,
  source       text not null default 'counter' check (source in ('counter', 'phone', 'store', 'contacts', 'import')),
  legacy_id    text unique,
  notes        text check (char_length(notes) <= 500),
  active       boolean not null default true,
  created_at   timestamptz not null default now()
);
create index customers_name_trgm on ph.customers using gin (name extensions.gin_trgm_ops);
create trigger audit_customers after update of credit_limit on ph.customers for each row execute function ph.audit();

-- الأدوية المزمنة: «علبتك قربت تخلص». last_bought بيتحدث لوحده مع كل بيع للعميل
create table ph.customer_meds (
  customer_id bigint not null references ph.customers (id),
  item_id     bigint not null references ph.items (id),
  every_days  integer not null check (every_days between 1 and 365),
  last_bought date,
  active      boolean not null default true,
  primary key (customer_id, item_id)
);
