create table ph.manufacturers (
  id   integer generated always as identity primary key,
  name text not null unique check (char_length(name) between 2 and 120)
);

create table ph.categories (
  id      smallint generated always as identity primary key,
  code    text not null unique check (code ~ '^[a-z0-9_]{2,40}$'),   -- نفس تصنيفات الموقع: antibiotic, pain_fever ...
  name_ar text not null check (char_length(name_ar) between 2 and 80)
);

-- المادة الفعالة + الشكل: أصناف نفس المجموعة بدايل لبعض
create table ph.generics (
  gkey        text primary key check (char_length(gkey) between 2 and 200),
  ingredients text not null check (char_length(ingredients) between 2 and 400),
  form        text
);

create table ph.items (
  -- الأصناف المنقولة من فارمافلاي بتاخد نفس رقمها (صور الموقع والبوت متسجلة بيه)، والجديدة بتبدأ من مليون
  id              bigint generated by default as identity (start with 1000000) primary key,
  name_en         text not null check (char_length(name_en) between 2 and 250),
  name_ar         text check (char_length(name_ar) <= 250),
  spoken_name     text check (char_length(spoken_name) <= 120),          -- إزاي الموبايل ينطقه
  form            text check (char_length(form) <= 20),                  -- tab, cap, syrup, inj, cream ...
  strength        text check (char_length(strength) <= 60),
  manufacturer_id integer references ph.manufacturers (id),
  category_id     smallint references ph.categories (id),
  gkey            text references ph.generics (gkey),
  pack_parts      integer not null default 1 check (pack_parts between 1 and 10000),  -- كام وحدة في العلبة
  pack_name       text not null default 'علبة' check (char_length(pack_name) <= 20),
  unit_name       text not null default 'شريط' check (char_length(unit_name) <= 20),
  sell_by_unit    boolean not null default true,                          -- بيتباع بالشريط؟
  public_price    numeric(12, 2) check (public_price > 0),                -- سعر العلبة الحالي (التشغيلة القديمة بسعرها)
  vat_rate        numeric(5, 2) not null default 0 check (vat_rate between 0 and 100),
  needs_rx        boolean not null default false,
  is_controlled   boolean not null default false,                         -- جدول: البيع محتاج روشتة ويتسجل في السجل
  is_fridge       boolean not null default false,
  track_stock     boolean not null default true,                          -- false = خدمة (قياس ضغط مثلًا)
  active          boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index items_name_en_trgm on ph.items using gin (name_en extensions.gin_trgm_ops);
create index items_name_ar_trgm on ph.items using gin (name_ar extensions.gin_trgm_ops);
create index on ph.items (gkey);
create index on ph.items (category_id);

create table ph.item_barcodes (
  barcode text primary key check (barcode ~ '^[0-9A-Za-z-]{4,40}$'),
  item_id bigint not null references ph.items (id)
);
create index on ph.item_barcodes (item_id);

-- كل تغيير في سعر الجمهور بيتسجل: إمتى، من كام لكام، وجه منين
create table ph.price_changes (
  id         bigint generated always as identity primary key,
  item_id    bigint not null references ph.items (id),
  old_price  numeric(12, 2),
  new_price  numeric(12, 2),
  changed_at timestamptz not null default now(),
  source     text not null default 'manual' check (source in ('manual', 'purchase', 'import')),
  by_user    uuid default auth.uid()
);

create function ph.log_price_change() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.public_price is distinct from old.public_price then
    insert into ph.price_changes (item_id, old_price, new_price, source)
    values (new.id, old.public_price, new.public_price,
            coalesce(nullif(current_setting('ph.price_source', true), ''), 'manual'));
  end if;
  new.updated_at := now();
  return new;
end $$;
create trigger items_price_log before update on ph.items for each row execute function ph.log_price_change();
create trigger price_changes_locked before update or delete on ph.price_changes for each row execute function ph.forbid_change();

-- البحث: باركود بالظبط، أو جزء من الاسم عربي أو إنجليزي (الأقرب الأول)
create function ph.find_items(q text, max_rows integer default 30)
returns table (id bigint, name_en text, name_ar text, public_price numeric, pack_parts integer, score real)
language sql stable security definer set search_path = '' as $$
  select i.id, i.name_en, i.name_ar, i.public_price, i.pack_parts, 1.0::real
  from ph.item_barcodes b join ph.items i on i.id = b.item_id
  where b.barcode = btrim(q) and i.active and ph.has_role(array['owner', 'manager', 'pharmacist', 'cashier'])
  union all
  select * from (
    select i.id, i.name_en, i.name_ar, i.public_price, i.pack_parts,
           greatest(extensions.similarity(i.name_en, q), extensions.similarity(coalesce(i.name_ar, ''), q)) as score
    from ph.items i
    where i.active
      and ph.has_role(array['owner', 'manager', 'pharmacist', 'cashier'])
      and (i.name_en ilike '%' || btrim(q) || '%' or i.name_ar ilike '%' || btrim(q) || '%'
           or extensions.similarity(i.name_en, q) > 0.3)
    order by score desc, i.name_en
    limit max_rows
  ) s
$$;
